"""Generates src/profiles.js (students; a `name` column is optional) from:
  - course-members.json  (the Course Agent's COURSE_ROSTER_PATH, schema 1): uses department, keywords, project_ideas
  - students.csv         (columns: code,team,interests,skills,project; lists separated by ';')
Usage: python3 tools/roster2profiles.py /path/course-members.json   |   python3 tools/roster2profiles.py tools/students.csv
"""
import csv,json,pathlib,sys
src=pathlib.Path(sys.argv[1]);out=[]
if src.suffix.lower()==".json":
    data=json.load(open(src))
    for i,m in enumerate([m for m in data["members"] if m.get("course_status","active")=="active"]):
        kw=[k.strip() for k in m.get("keywords",[]) if k.strip()];ideas=[p.strip() for p in m.get("project_ideas",[]) if p.strip()]
        out.append({"code":f"S{i+1:02d}","team":m.get("department","—"),"interests":kw[:3] or ["agents"],
                    "skills":[m.get("department","—")]+kw[3:5],"project":ideas[0] if ideas else "a cognitive agents project","alt":ideas[1:],"active":True})
else:
    for i,r in enumerate(csv.DictReader(open(src,encoding="utf-8"))):
        L=lambda s:[x.strip() for x in (s or "").split(";") if x.strip()]
        weeks={k:v.strip() for k,v in r.items() if k and k.upper().startswith("W") and k[1:].isdigit() and v and v.strip()}
        wk=[weeks[k] for k in sorted(weeks)]
        project=(r.get("project") or r.get("final_project") or (wk[-1] if wk else "") or "a cognitive agents project").strip()
        out.append({"code":(r.get("code") or f"S{i+1:02d}").strip(),"team":(r.get("team") or "—").strip(),
                    "interests":L(r.get("interests")) or [w[:40] for w in wk[-3:]] or ["agents"],
                    "skills":L(r.get("skills")) or [w[:40] for w in wk[:2]] or ["—"],
                    "project":project,"alt":wk,"bio":(r.get("bio") or "").strip()[:400],"site":(r.get("site") or "").strip(),"name":(r.get("name") or "").strip(),"active":(r.get("active") or "1").strip() not in ("0","false","no","")})
dst=pathlib.Path(__file__).resolve().parent.parent/"src"/"profiles.js"
dst.write_text("// PROFILES generated by tools/roster2profiles.py (no names or emails).\nconst PROFILES="+json.dumps(out,ensure_ascii=False)+";\n",encoding="utf-8")
print(len(out),"profiles ->",dst)
